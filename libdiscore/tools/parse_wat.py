#!/usr/bin/env python3
"""Inventory every element of the wabt --decompiler listing data/libdiscore.c.

Outputs:
  libdiscore/wasm-manifest.json  - every reserved/exported function (name, line range, size),
                                   every import, every data segment, module-level statistics
  (The byte-exact tools/data.bin is generated by parse_wasm_bin.py.)

Run:  python3 tools/parse_wat.py
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT.parent / "data" / "libdiscore.c"
OUT = ROOT / "wasm-manifest.json"


def unescape(s: str) -> bytes:
    out = bytearray()
    i = 0
    while i < len(s):
        c = s[i]
        if c == "\\" and i + 1 < len(s):
            h = s[i + 1]
            if (
                i + 2 < len(s)
                and h.lower() in "0123456789abcdef"
                and s[i + 2].lower() in "0123456789abcdef"
            ):
                out.append(int(s[i + 1 : i + 3], 16))
                i += 3
                continue
            out.extend(h.encode())
            i += 2
            continue
        out.extend(c.encode())
        i += 1
    return bytes(out)


FUNC_RE = re.compile(r"^(export )?function ([\w.]+)\(")


def main() -> int:
    lines = SRC.read_text(errors="replace").splitlines()
    n = len(lines)
    funcs, imports, non_fn_exports, data_segments = [], [], [], []
    blob = bytearray()
    i = 0
    while i < n:
        line = lines[i]
        stripped = line.strip()
        if stripped.startswith("import "):
            imports.append(stripped)
            i += 1
            continue
        if stripped.startswith(("export memory", "export table", "export global")):
            non_fn_exports.append(stripped)
            i += 1
            continue
        if stripped.startswith("data ") and "offset: " in stripped:
            j = i
            # the payload may start on the same line or the next one; scan until `";`
            while j < n and not lines[j].strip().endswith('";'):
                j += 1
            payload = ""
            for l in lines[i : j + 1]:
                s = l.strip()
                s = re.sub(r"^data [\w.\-]+\(offset: \d+\)\s*=\s*", "", s)  # segment header
                if s == "":
                    continue
                s = re.sub(r"^\"(.*)\";?$", r"\1", s)  # per-line quotes (wabt never splits an escape)
                payload += s
            off = int(re.search(r"offset: (\d+)", lines[i]).group(1))
            content = unescape(payload)
            data_segments.append(
                {
                    "name": re.search(r"^data ([\w.\-]+)", lines[i]).group(1),
                    "offset": off,
                    "size": len(content),
                    "line_start": i + 1,
                    "line_end": j + 1,
                }
            )
            end = off + len(content)
            if end > len(blob):
                blob.extend(bytes(end - len(blob)))
            blob[off : end] = content
            i = j + 1
            continue
        m = FUNC_RE.match(stripped)
        if m:
            name = m.group(2)
            depth = 0
            j = i
            while j < n:
                depth += lines[j].count("{") - lines[j].count("}")
                if j > i and depth <= 0 and lines[j].strip() == "}":
                    break
                j += 1
            funcs.append(
                {
                    "name": name,
                    "exported": bool(m.group(1)),
                    "line_start": i + 1,
                    "line_end": j + 1,
                    "lines": j + 1 - i,
                }
            )
            i = j + 1
            continue
        i += 1

    manifest = {
        "source": str(SRC),
        "counts": {
            "functions": len(funcs),
            "exported_functions": sum(f["exported"] for f in funcs),
            "exports_non_function": len(non_fn_exports),
            "imports": len(imports),
            "data_segments": len(data_segments),
            "total_function_lines": sum(f["lines"] for f in funcs),
            "listing_lines": n,
        },
        "exports": {"non_function": non_fn_exports, "functions": [f["name"] for f in funcs if f["exported"]]},
        "imports": imports,
        "data_segments": data_segments,
        "functions": funcs,
    }
    OUT.write_text(json.dumps(manifest, separators=(",", ":")))
    print(f"inventoried {len(funcs)} functions ({manifest['counts']['total_function_lines']} listing lines), "
          f"{len(imports)} imports, {len(data_segments)} data segments, listing blob={len(blob)} bytes -> {OUT.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
